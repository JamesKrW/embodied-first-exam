# --------------------------------------------------------------------------------------------------- small helpers
def now():
    return time.time()


def rl(p):
    try:
        return os.readlink(p)
    except OSError:
        return None


def read(p):
    try:
        with open(p) as f:
            return f.read()
    except OSError:
        return None


def stat_id(p):
    try:
        st = os.stat(p)
        return (st.st_dev, st.st_ino)
    except OSError:
        return None


def stat_of(base):
    """(starttime, utime+stime) of the process or thread at /proc path `base`, or None."""
    s = read(base + "/stat")
    if not s:
        return None
    try:
        f = s.rsplit(")", 1)[1].split()
        return int(f[19]), int(f[11]) + int(f[12])
    except (IndexError, ValueError):
        return None


def proc_stat(pid):
    return stat_of(f"{PROC}/{pid}")


def status(pid):
    s = read(f"{PROC}/{pid}/status")
    if not s:
        return {}
    d = {}
    for line in s.splitlines():
        k, _, v = line.partition(":")
        d[k] = v.strip()
    return d


def kb(v):
    try:
        return int((v or "0").split()[0])
    except (ValueError, IndexError):
        return 0


def append(name, obj):
    with open(os.path.join(REC, name), "a") as f:
        f.write(json.dumps(obj, separators=(",", ":")) + "\n")


def write_json(path, obj):
    tmp = path + ".tmp"
    with open(tmp, "w") as f:
        json.dump(obj, f, indent=1)
    os.replace(tmp, path)


def event(kind, **kw):
    kw.update(t=round(now(), 2), event=kind)
    append("events.jsonl", kw)


def clock(t, start, timeout):
    """The agent's clock for usage.json: seconds since `start` (the trial environment's start)
    and, with the task's time limit, the time left and the deadline. Counted from before the agent's session starts, so
    `time_left_s` is never more than the agent really has."""
    out = {"elapsed_s": round(max(0.0, t - start), 1)}
    if timeout:
        out.update(time_limit_s=int(timeout), time_left_s=round(max(0.0, start + timeout - t), 1),
                   deadline_utc=time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(start + timeout)))
    return out


def usage_caps(lim):
    """usage.json `caps`: the agent's own container's (CPU: a throttle; memory: the kernel's OOM killer; processes; disk;
    GPU memory, None without a GPU), as limits.json gives them."""
    main = (lim.get("caps") or {}).get("main") or {}
    return {k: main.get(k) for k in ("cpus", "memory_gb", "pids", "disk_gb", "gpu_memory_gb")}


def usage_limits(lim, tol=rcb_limits.TOLERANCE):
    """usage.json `limits`: the scope's GPU-memory and disk caps and the tolerance a measurement is over a cap by."""
    return {"gpu_memory_gb": lim.get("gpu_memory_gb"), "disk_gb": lim.get("disk_gb"), "tolerance": tol}


def open_in_root(root, rel):
    """A read-only fd of the regular file `rel` under the directory `root` (a container's /proc/<pid>/root), never
    through a symbolic link (an absolute link would resolve in the monitor's own file system), or None."""
    fd = None
    try:
        fd = os.open(root, os.O_RDONLY | os.O_DIRECTORY)
        parts = rel.split("/")
        for part in parts[:-1]:
            nfd = os.open(part, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW, dir_fd=fd)
            os.close(fd)
            fd = nfd
        f = os.open(parts[-1], os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK, dir_fd=fd)
        if not stat_mod.S_ISREG(os.fstat(f).st_mode):
            os.close(f)
            return None
        return f
    except OSError:
        return None
    finally:
        if fd is not None:
            os.close(fd)


class SessionLogCopy:
    """Append-only copy of the agent's session log into the record. State (inode, offset, segment, tail hash)
    lives in the record's state.json, so a restarted monitor goes on where it was."""

    def __init__(self, state=None):
        self.s = dict(state or {"ino": None, "off": 0, "seg": 0, "tail": "", "copied": 0, "gone": False})

    def step(self, root):
        import hashlib
        fd = open_in_root(root, SESSION_LOG)
        if fd is None:
            if self.s["ino"] is not None and not self.s["gone"]:
                self.s["gone"] = True
                event("session_log_removed", copied=self.s["copied"], segment=self.s["seg"])
            return
        try:
            st = os.fstat(fd)
            s = self.s

            def tail_of(end):
                os.lseek(fd, max(0, end - SESSION_LOG_TAIL), 0)
                return hashlib.sha256(os.read(fd, min(SESSION_LOG_TAIL, end))).hexdigest()

            if s["ino"] is not None and (st.st_ino != s["ino"] or st.st_size < s["off"] or s["gone"]
                                         or (s["off"] and tail_of(s["off"]) != s["tail"])):
                event("session_log_rewritten", copied=s["off"], size=st.st_size, segment=s["seg"] + 1,
                      why="replaced" if st.st_ino != s["ino"] else "truncated" if st.st_size < s["off"] else
                      "back after removal" if s["gone"] else "rewritten")
                s.update(off=0, seg=s["seg"] + 1, tail="")
            s.update(ino=st.st_ino, gone=False)
            n = min(st.st_size - s["off"], SESSION_LOG_MAX - s["copied"])
            if n <= 0:
                return
            os.lseek(fd, s["off"], 0)
            data = b""
            while len(data) < n:
                chunk = os.read(fd, n - len(data))
                if not chunk:
                    break
                data += chunk
            d = os.path.join(REC, "session_log")
            os.makedirs(d, exist_ok=True)
            with open(os.path.join(d, "%d.jsonl" % s["seg"]), "ab") as out:
                out.write(data)
            s["off"] += len(data)
            s["copied"] += len(data)
            s["tail"] = tail_of(s["off"])
        finally:
            os.close(fd)


def own_cgroup():
    """Whether this container has a cgroup of its own. It has none when its runtime could not create one: rootless
    podman where the user's cgroup is not delegated to it (a Slurm job step, for one) or cgroup v1; the container then
    shares its parent's (conmon's) cgroup, and its caps are not applied. Such a container in the host PID namespace
    (`pid: host`) cannot be stopped by its runtime: podman stops it by signalling the processes of its cgroup (`kill
    --all`), which are none, so it stays "Stopping" ("given PID did not die within timeout"). The monitor then ends
    itself after the seal (Monitor.linger). Unknown (unreadable): True, the runtime's stop is trusted."""
    mine, parent = read(f"{PROC}/self/cgroup"), read(f"{PROC}/{os.getppid()}/cgroup")
    return not mine or not parent or mine != parent


def no_dump():
    """Not dumpable: without CAP_SYS_PTRACE nobody (not even the same uid) can open /proc/<monitor>/{root,mem,fd}."""
    try:
        ctypes.CDLL(None, use_errno=True).prctl(4, 0, 0, 0, 0)    # PR_SET_DUMPABLE = 4
    except Exception:
        pass


# --------------------------------------------------------------------------------------------------- NVML
class Nvml:
    """Per-process GPU memory (host PIDs: the monitor runs in the host PID namespace) and per-card use, via libnvidia-ml
    (ctypes; no nvidia-smi child processes)."""

    class Proc(ctypes.Structure):
        _fields_ = [("pid", ctypes.c_uint), ("usedGpuMemory", ctypes.c_ulonglong),
                    ("gpuInstanceId", ctypes.c_uint), ("computeInstanceId", ctypes.c_uint)]

    class Proc1(ctypes.Structure):
        _fields_ = [("pid", ctypes.c_uint), ("usedGpuMemory", ctypes.c_ulonglong)]

    class Mem(ctypes.Structure):
        _fields_ = [("total", ctypes.c_ulonglong), ("free", ctypes.c_ulonglong), ("used", ctypes.c_ulonglong)]

    def __init__(self):
        self.lib = ctypes.CDLL("libnvidia-ml.so.1")
        if self.lib.nvmlInit_v2() != 0:
            raise RuntimeError("nvmlInit failed")
        n = ctypes.c_uint(0)
        self.lib.nvmlDeviceGetCount_v2(ctypes.byref(n))
        self.handles = []
        for i in range(n.value):
            h = ctypes.c_void_p()
            if self.lib.nvmlDeviceGetHandleByIndex_v2(i, ctypes.byref(h)) == 0:
                self.handles.append(h)
        self.fns = []
        for name, st in (("nvmlDeviceGetComputeRunningProcesses_v3", self.Proc),
                         ("nvmlDeviceGetGraphicsRunningProcesses_v3", self.Proc),
                         ("nvmlDeviceGetComputeRunningProcesses_v2", self.Proc),
                         ("nvmlDeviceGetGraphicsRunningProcesses_v2", self.Proc),
                         ("nvmlDeviceGetComputeRunningProcesses", self.Proc1),
                         ("nvmlDeviceGetGraphicsRunningProcesses", self.Proc1)):
            kind = "compute" if "Compute" in name else "graphics"
            if any(k == kind for k, _, _ in self.fns):
                continue
            try:
                self.fns.append((kind, getattr(self.lib, name), st))
            except AttributeError:
                pass

    def sample(self):
        """({host pid: MiB}, {card index: (used MiB, total MiB)}, {host pids whose memory NVML does not tell})."""
        per, cards, unknown = {}, {}, set()
        for i, h in enumerate(self.handles):
            m = self.Mem()
            if self.lib.nvmlDeviceGetMemoryInfo(h, ctypes.byref(m)) == 0:
                cards[i] = (m.used // 2 ** 20, m.total // 2 ** 20)
            seen = {}
            for _kind, fn, st in self.fns:
                cnt = ctypes.c_uint(0)
                rc = fn(h, ctypes.byref(cnt), None)
                if rc not in (0, 7):                 # 7 = NVML_ERROR_INSUFFICIENT_SIZE: cnt now holds the count
                    continue
                cnt = ctypes.c_uint(cnt.value + 16)
                arr = (st * cnt.value)()
                if fn(h, ctypes.byref(cnt), arr) != 0:
                    continue
                for k in range(cnt.value):
                    mem = arr[k].usedGpuMemory
                    if mem >= 2 ** 63:               # NVML_VALUE_NOT_AVAILABLE (MIG / vGPU / WSL): not a zero
                        unknown.add(arr[k].pid)
                        mib = 0
                    else:
                        mib = mem // 2 ** 20
                    seen[arr[k].pid] = max(seen.get(arr[k].pid, 0), mib)   # a C+G process is in both lists
            for p, v in seen.items():
                per[p] = per.get(p, 0) + v
        return per, cards, unknown


