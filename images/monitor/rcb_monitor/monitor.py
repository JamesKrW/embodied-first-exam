class OomWatch:
    """Kernel OOM kills of the watched containers, from each one's cgroup v2 `memory.events`:
      oom       times the cgroup's memory reached its own limit (memory.max) and an allocation was about to fail
      oom_kill  processes of the cgroup killed by any OOM killer (its own limit's, an enclosing cgroup's, the host's)
    A kill whose `oom` counter rose with it (or within OOM_CAP_WINDOW_SEC before) happened at the container's own cap
    (`cause: "cap"`); one without is the host's or an enclosing cgroup's OOM killer (`cause: "host"`), which the
    container did not cause by its own use (PROTOCOL §6: nothing another trial does can fail a trial).

    The counters live and die with the cgroup, and a container whose main process is killed is gone (and restarted by
    compose with fresh counters) within milliseconds. So the files are read by this object's own thread, every
    OOM_COLD_SEC, at once when the kernel signals a change (poll: memory.events notifies), and every OOM_HOT_SEC for a
    while after any change (the `max` counter rises under memory pressure, before a kill). A kill that removes the
    cgroup within about a millisecond can still be missed: such a kill is then in no record.

    scan() reads every file once; the sampler calls it at each tick when the thread does not run (the tests). The
    thread ends when the record is sealed."""

    def __init__(self):
        self.lock = threading.Lock()
        self.w = {}                  # cgroup dir -> {"role", "scope", "fd", "kill", "oom", "sig", "cap_t", "seen"}
        self.hot_until = 0.0
        self.thread = None
        self.stopped = False         # set at the seal: the record is closed, like the samples

    def watch(self, cg, role, scope, t, service=None):
        """The sampler saw this container's cgroup at time t."""
        with self.lock:
            e = self.w.get(cg)
            if e is None:
                e = self.w[cg] = {"fd": None, "kill": None, "oom": None, "sig": None, "cap_t": None}
            e.update(role=role, scope=bool(scope), seen=t, service=service)

    @staticmethod
    def _close(e):
        if e["fd"] is not None:
            try:
                os.close(e["fd"])
            except OSError:
                pass
            e["fd"] = None

    def _read(self, cg, e):
        """The counters of the cgroup's memory.events ({} when the file cannot be read: the container is not up).
        A file that stops answering belonged to a cgroup that is gone; the same path opened again is a new cgroup (the
        container restarted: another directory, by its inode and creation time), whose counters all belong to the
        trial: they are compared with 0. The same cgroup opened again keeps what was already counted."""
        for _ in (0, 1):
            try:
                if e["fd"] is None:
                    e["fd"] = os.open(cg + "/memory.events", os.O_RDONLY)
                    st = os.stat(cg)
                    ident = (st.st_dev, st.st_ino, st.st_ctime_ns)
                    if e["sig"] is not None and ident != e.get("ident"):
                        e["kill"] = e["oom"] = 0     # read before, gone, here again: another instance of the cgroup
                    e["ident"] = ident
                os.lseek(e["fd"], 0, os.SEEK_SET)
                out = {}
                for line in os.read(e["fd"], 8192).decode("ascii", "replace").splitlines():
                    k, _, v = line.partition(" ")
                    if v.strip().isdigit():
                        out[k] = int(v)
                return out
            except OSError:
                self._close(e)
        return {}

    def scan(self):
        """Read every watched file once and record the kills since the last reading. True when a counter changed."""
        changed = False
        with self.lock:
            t = now()
            for cg, e in list(self.w.items()):
                if t - e["seen"] > OOM_FORGET_SEC:
                    self._close(e)
                    del self.w[cg]
                    continue
                c = self._read(cg, e)
                if "oom_kill" not in c:
                    continue
                kill, oom = c["oom_kill"], c.get("oom", 0)
                sig = (kill, oom, c.get("max", 0))
                if e["kill"] is None or kill < e["kill"] or oom < e["oom"]:
                    # the first reading is the baseline; counters that went back are a new cgroup under the same path
                    e["kill"], e["oom"] = (kill, oom) if e["kill"] is None else (0, 0)
                changed |= sig != e["sig"]
                if oom > e["oom"]:
                    e["cap_t"] = t
                if kill > e["kill"]:
                    at_cap = e["cap_t"] is not None and t - e["cap_t"] <= OOM_CAP_WINDOW_SEC
                    kw = {"role": e["role"], "service": e.get("service"), "scope": e["scope"], "count": kill - e["kill"],
                          "cause": "cap" if at_cap else "host", "cap_hits": oom - e["oom"]}
                    for name, key in (("memory.max", "memory_cap_gb"), ("memory.current", "memory_current_gb")):
                        v = (read(cg + "/" + name) or "").strip()      # evidence only: the cause is the counters'
                        if v.isdigit():
                            kw[key] = round(int(v) / GIB, 3)
                    event("oom", **kw)
                e["kill"], e["oom"], e["sig"] = kill, oom, sig
        return changed

    def start(self):
        self.thread = threading.Thread(target=self._loop, name="rcb-oom-watch", daemon=True)
        self.thread.start()

    def _loop(self):
        said = False
        while not self.stopped:
            try:
                if self.scan():
                    self.hot_until = now() + OOM_HOT_FOR_SEC
                if now() < self.hot_until:
                    time.sleep(OOM_HOT_SEC)
                    continue
                with self.lock:
                    fds = [e["fd"] for e in self.w.values() if e["fd"] is not None]
                if not fds:
                    time.sleep(OOM_COLD_SEC)
                    continue
                p = select.poll()                     # memory.events notifies its readers (POLLPRI) when it changes
                for fd in fds:
                    p.register(fd, select.POLLPRI | select.POLLERR)
                if p.poll(OOM_COLD_SEC * 1000):
                    self.hot_until = now() + OOM_HOT_FOR_SEC
            except Exception as e:                    # never stop watching
                if not said:
                    said = True
                    try:
                        event("error", why=f"oom watch: {type(e).__name__}: {e}"[:300])
                    except Exception:
                        pass
                time.sleep(OOM_COLD_SEC)


# --------------------------------------------------------------------------------------------------- CPU backstop
class Throttler:
    """The CPU backstop (RCB_LIMITS_ENFORCE=1): a container whose CPU use is over its cap is duty-cycled, cpulimit-style.
    Every THROTTLE_PERIOD_SEC its processes get SIGCONT, run for `frac` of the period, then get SIGSTOP for the rest
    (parents stopped before their children, children continued before their parents, so that a shell waiting for a
    child never sees it stopped). frac = cap / demand, where demand is the CPU the container would use unthrottled: at
    each sample, the CPU it used over the last tick divided by the share it was let run. When the demand is back under
    the cap the container is released (SIGCONT to all). Its own thread; every process is let go (SIGCONT) when the
    container is released, at the seal, when the monitor is stopped, and by a restarted monitor (Monitor.restore).
    Never PID 1 or what started with it (Monitor.spared). Signals go through a pidfd where the kernel has them (a PID
    reused by another process is never signalled), else after a check of the process's start time."""

    def __init__(self, mon):
        self.mon = mon
        self.lock = threading.Lock()
        self.active = {}          # mnt ns -> {"frac", "cap", "since", "service", "role", "keep", "procs": {pid: (start, fd)},
        #                           "refreshed"}
        self.thread = None
        self.stopped = False
        self.said = set()

    # ---- engaging and releasing (the sampler's thread)
    def engage(self, mnt, g, cap, demand, t):
        frac = max(THROTTLE_MIN_FRACTION, min(1.0, cap / demand)) if demand > 0 else 1.0
        with self.lock:
            e = self.active.get(mnt)
            if e is None:
                keep = {(p, (proc_stat(p) or (None,))[0]) for p in self.mon.spared(g["pids"])}
                e = self.active[mnt] = {"frac": frac, "cap": cap, "since": now(), "service": g.get("service"),
                                        "role": g["role"], "keep": keep, "procs": {}, "refreshed": 0.0}
                self._refresh(mnt, e, g["pids"])
                event("throttle_start", resource="cpu", service=g.get("service"), role=g["role"], value=round(demand, 2),
                      cap=cap, fraction=round(frac, 3))
            else:
                e["frac"] = frac
        self.start()

    def adjust(self, mnt, used):
        """A sample of a throttled container: `used` = CPUs it used over the last tick. Released when its demand
        (used / its share) fits under the cap; else its share follows the demand."""
        with self.lock:
            e = self.active.get(mnt)
            if e is None:
                return
            demand = used / e["frac"] if e["frac"] > 0 else used
            frac, cap = e["frac"], e["cap"]
        if demand <= cap:
            self.release(mnt, "demand under the cap", demand=round(demand, 2))
        else:
            with self.lock:
                if mnt in self.active:
                    self.active[mnt]["frac"] = max(THROTTLE_MIN_FRACTION, min(1.0, frac * cap / max(used, 1e-6)
                                                                              if used > 0 else 1.0))

    def release(self, mnt, why, **kw):
        with self.lock:
            e = self.active.pop(mnt, None)
            if e is None:
                return
            self._signal(e, signal.SIGCONT)
            self._close(e)
        event("throttle_end", resource="cpu", service=e["service"], role=e["role"], why=why,
              sec=round(now() - e["since"], 1), **kw)

    def release_all(self, why):
        for mnt in list(self.active):
            self.release(mnt, why)

    def throttled(self, mnt):
        return mnt in self.active

    # ---- the processes of a throttled container
    def _refresh(self, mnt, e, pids=None):
        """Look up the container's processes again (new ones started since are throttled too, gone ones dropped)."""
        if pids is None:
            pids = []
            try:
                names = os.listdir(PROC)
            except OSError:
                names = []
            for d in names:
                if d.isdigit() and rl(f"{PROC}/{d}/ns/mnt") == mnt:
                    pids.append(int(d))
        keep_pids = {p for p, _ in e["keep"]}
        old = e["procs"]
        new = {}
        for p in pids:
            if p in keep_pids:
                continue
            ps = proc_stat(p)
            if ps is None:
                continue
            if p in old and old[p][0] == ps[0]:
                new[p] = old.pop(p)
                continue
            new[p] = (ps[0], self._pidfd(p, ps[0]))
        for _, fd in old.values():
            if fd is not None:
                try:
                    os.close(fd)
                except OSError:
                    pass
        e["procs"], e["refreshed"] = new, now()

    @staticmethod
    def _pidfd(p, start):
        if PROC != "/proc" or not hasattr(os, "pidfd_open"):
            return None
        try:
            fd = os.pidfd_open(p)
        except OSError:
            return None
        ps = proc_stat(p)
        if not ps or ps[0] != start:        # the PID now names another process
            os.close(fd)
            return None
        return fd

    @staticmethod
    def _close(e):
        for _, fd in e["procs"].values():
            if fd is not None:
                try:
                    os.close(fd)
                except OSError:
                    pass
        e["procs"] = {}

    def _signal(self, e, sig):
        order = sorted(e["procs"].items(), key=lambda kv: kv[1][0], reverse=(sig == signal.SIGCONT))
        for p, (start, fd) in order:
            try:
                if fd is not None:
                    signal.pidfd_send_signal(fd, sig)
                else:
                    ps = proc_stat(p)
                    if not ps or ps[0] != start:
                        continue
                    os.kill(p, sig)
            except ProcessLookupError:
                pass
            except OSError as err:
                if ("signal", type(err).__name__) not in self.said:
                    self.said.add(("signal", type(err).__name__))
                    event("backstop_error", resource="cpu", why=f"signal to a process: {type(err).__name__}: {err}"[:300])

    # ---- the thread
    def start(self):
        if self.thread is None and not self.stopped and self.mon.threads:
            self.thread = threading.Thread(target=self._loop, name="rcb-throttle", daemon=True)
            self.thread.start()

    def cycle(self, sleep=time.sleep, clock=time.monotonic):
        """One period: every throttled container runs for its share of it, then is stopped for the rest."""
        t0 = clock()
        with self.lock:
            items = list(self.active.items())
            for mnt, e in items:
                if now() - e["refreshed"] >= THROTTLE_REFRESH_SEC:
                    self._refresh(mnt, e)
                self._signal(e, signal.SIGCONT)
        for mnt, e in sorted(items, key=lambda kv: kv[1]["frac"]):
            wait = t0 + e["frac"] * THROTTLE_PERIOD_SEC - clock()
            if wait > 0:
                sleep(wait)
            with self.lock:
                if self.active.get(mnt) is e and e["frac"] < 1.0:
                    self._signal(e, signal.SIGSTOP)
        wait = t0 + THROTTLE_PERIOD_SEC - clock()
        if wait > 0:
            sleep(wait)

    def _loop(self):
        try:
            while not self.stopped:
                if not self.active:
                    time.sleep(0.2)
                    continue
                try:
                    self.cycle()
                except Exception as err:          # never leave a container stopped
                    with self.lock:
                        for e in self.active.values():
                            self._signal(e, signal.SIGCONT)
                    if "loop" not in self.said:
                        self.said.add("loop")
                        event("backstop_error", resource="cpu", why=f"throttle: {type(err).__name__}: {err}"[:300])
                    time.sleep(0.5)
        finally:
            with self.lock:
                for e in self.active.values():
                    self._signal(e, signal.SIGCONT)

    def stop(self, why):
        """The seal or the monitor's own end: every throttled process is let go, the thread ends."""
        self.stopped = True
        self.release_all(why)


